const translations = { en: english, fr: french };

export function getStoredLanguage(): Language {
  return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'fr' ? 'fr' : 'en';
}

export function storeLanguage(language: Language): void {
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
}

export function localeForLanguage(language: Language): string {
  return language === 'fr' ? 'fr-FR' : 'en-US';
}

export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function translateClaudeWindowLabel(language: Language, key: string, label: string): string {
  if (language === 'en') return label;
  if (key === 'session') return translate(language, 'claudeSession');
  if (key === 'weekly_all') return translate(language, 'claudeWeekly');
  if (key === 'weekly_scoped') return label.replace(/^Weekly/, translate(language, 'claudeWeekly'));
  return label;
}
